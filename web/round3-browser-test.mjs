import assert from 'node:assert/strict'
import { expect } from 'playwright/test'
import { execFileSync } from 'node:child_process'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

export async function verifyRound3({ browser, origin, directOrigin, api, test, report, bootstrap, fixtureJpeg, evidence }) {
  const context = await browser.newContext({ viewport: { width: 375, height: 812 }, locale: 'zh-CN', reducedMotion: 'reduce' })
  const errors = []
  await context.route('**/*', route => {
    const url = route.request().url()
    if (/^https?:/.test(url) && new URL(url).origin !== origin) { report.externalRequests.push(url); return route.abort('blockedbyclient') }
    return route.continue()
  })
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(String(error)))
  const go = async route => page.goto(origin + '/#' + route, { waitUntil: 'networkidle' })
  const response = (pathname, method) => page.waitForResponse(r => new URL(r.url()).pathname === '/api' + pathname && r.request().method() === method)
  const choose = async (input, name) => { await input.click(); await page.getByRole('option', { name, exact: true }).click() }
  const namesRoot = input => input.locator('xpath=ancestor::div[contains(concat(" ",normalize-space(@class)," ")," names-editor ")]')
  async function clearNames(input) {
    await input.fill('')
    const buttons = namesRoot(input).locator('.name-remove')
    while (await buttons.count()) await buttons.first().click()
  }
  async function pasteNames(input, value) {
    await input.focus()
    await input.evaluate((element, text) => {
      const clipboardData = new DataTransfer(); clipboardData.setData('text/plain', text)
      element.dispatchEvent(new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true }))
    }, value)
  }
  const point = await api('/points', { method: 'POST', body: { name: '本轮甲点位', communityId: bootstrap.communities[0].id, typeId: bootstrap.pointTypes[0].id, address: '甲地址', frequency: 'weekly' } })
  const excluded = await api('/points', { method: 'POST', body: { ...point, name: '不应导出的乙点位', address: '乙地址' } })
  let fixedRemediation, temporaryRemediation
  const originalSettings = await api('/settings')
  try {
    await test('R3 fixed-point remediation activity, point history and read-only photos', async () => {
      await go('/points/' + point.id)
      await expect(page.getByTestId('photo-file-input')).toHaveCount(0)
      await expect(page.getByRole('button', { name: /删除照片|添加照片|添加图片/ })).toHaveCount(0)
      await page.getByTestId('point-new-activity').click()
      await expect(page.getByTestId('activity-selected-point')).toContainText(point.name)
      await page.getByTestId('activity-name').fill('甲点位整治')
      await choose(page.getByTestId('activity-remediation-type'), bootstrap.remediationTypes[0].name)
      await page.getByTestId('activity-content').fill('甲点位清理内容')
      await page.getByRole('button', { name: '更多信息', exact: true }).click()
      const people = page.getByLabel('参加单位及人员', { exact: true })
      await pasteNames(people, '环卫所，张三,李四、王五；赵六 钱七\n孙八')
      await people.press('Enter')
      await expect(namesRoot(people).locator('.name-edit-tag')).toHaveCount(7)
      const saved = response('/activities', 'POST')
      await page.getByTestId('activity-save').click()
      fixedRemediation = await (await saved).json()
      assert.equal(fixedRemediation.activity.pointId, point.id)
      assert.equal(fixedRemediation.activity.location, point.address)
      assert.equal(fixedRemediation.activity.participants, '环卫所 张三 李四 王五 赵六 钱七 孙八')
      await page.waitForURL('**/#/activities/' + fixedRemediation.activity.id)
      await expect(page.getByTestId('name-tags').filter({ hasText: '环卫所' })).toContainText('孙八')
      await go('/points/' + point.id)
      await expect(page.getByTestId('activity-history')).toContainText('甲点位整治')
      await page.getByTestId('activity-history').getByRole('link', { name: '查看全部' }).click()
      await expect(page.getByTestId('activity-row')).toHaveCount(1)
      assert(new URL(page.url().split('#')[1], origin).searchParams.get('pointId') === point.id)
    })

    await test('R3 temporary remediation activity draft, coordinates, failed atomic save and history', async () => {
      await go('/activities/new?template=remediation')
      await page.getByTestId('activity-temporary-mode').click()
      await page.getByTestId('activity-temporary-name').fill('本轮临时丙点位')
      await choose(page.getByTestId('activity-temporary-community'), bootstrap.communities[0].name)
      await choose(page.getByTestId('activity-temporary-type'), bootstrap.pointTypes[0].name)
      await page.getByTestId('activity-temporary-address').fill('丙地址')
      await page.getByTestId('activity-temporary-coordinates').fill('88.893426,29.274331')
      await expect(page.getByRole('link', { name: '选取', exact: true })).toHaveAttribute('href', 'https://ditu.gaode.com/ssr/coordinate-picker')
      await page.getByTestId('activity-name').fill('丙点位整治')
      await choose(page.getByTestId('activity-remediation-type'), bootstrap.remediationTypes[0].name)
      await page.getByTestId('activity-content').fill('丙点位清理内容')
      await page.getByRole('button', { name: '更多信息', exact: true }).click()
      await pasteNames(page.getByLabel('参加单位及人员', { exact: true }), '甲单位，张三 李四\n')
      // Keep a still-uncommitted name in the draft without relying on blur.
      await page.getByLabel('参加单位及人员', { exact: true }).fill('末尾姓名')
      await page.reload({ waitUntil: 'networkidle' })
      await expect(page.getByTestId('activity-temporary-name')).toHaveValue('本轮临时丙点位')
      await expect(namesRoot(page.getByLabel('参加单位及人员', { exact: true }))).toContainText('末尾姓名')
      const wrong = await fetch(directOrigin + '/api/photos?phase=site', { method: 'PUT', headers: { 'Content-Type': 'image/jpeg' }, body: fixtureJpeg })
      const photo = await wrong.json()
      const failure = await fetch(directOrigin + '/api/activities', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name: '不应保存', typeId: bootstrap.activityTypes.find(type => type.template === 'remediation').id, remediation: { typeId: bootstrap.remediationTypes[0].id, beforePhotoIds: [photo.id] }, pointId: null, newPoint: { name: '应回滚的点位', communityId: point.communityId, typeId: point.typeId, address: '测试地址' }, date: bootstrap.today, content: '内容' }) })
      assert.equal(failure.status, 409)
      assert.match((await failure.json()).message, /阶段不符/)
      assert.equal((await api('/points?q=' + encodeURIComponent('应回滚的点位') + '&temporary=all')).total, 0)
      const saved = response('/activities', 'POST')
      await page.getByTestId('activity-save').click()
      temporaryRemediation = await (await saved).json()
      assert(temporaryRemediation.activity.pointTemporary)
      assert.equal(temporaryRemediation.activity.participants, '甲单位 张三 李四 末尾姓名')
      await page.waitForURL('**/#/activities/' + temporaryRemediation.activity.id)
      const created = await api('/points/' + temporaryRemediation.activity.pointId)
      assert.equal(created.point.frequency, 'irregular')
      assert.equal(created.point.longitude, 88.893426)
      assert.equal(created.activities[0].id, temporaryRemediation.activity.id)
      await go('/points/' + created.point.id)
      await expect(page.getByTestId('activity-history')).toContainText('丙点位整治')
      await page.getByRole('button', { name: '编辑', exact: true }).click()
      const editor = page.getByRole('dialog', { name: '编辑点位', exact: true })
      await expect(editor.getByTestId('photo-file-input')).toHaveCount(1)
      await expect(editor.getByRole('link', { name: '选取', exact: true })).toHaveAttribute('target', '_blank')
      await editor.getByRole('button', { name: '取消', exact: true }).click()
      await expect(page.getByTestId('photo-file-input')).toHaveCount(0)
    })

    await test('R3 point management downloads three ledgers with the selected owners only', async () => {
      await api('/activities', { method: 'POST', body: { name: '乙点位整治不应出现', pointId: excluded.id, typeId: bootstrap.activityTypes.find(type => type.template === 'remediation').id, remediation: { typeId: bootstrap.remediationTypes[0].id }, date: bootstrap.today, content: '乙点位内容' } })
      for (const current of [point, excluded]) {
        await api('/inspections', { method: 'POST', body: { pointId: current.id, date: bootstrap.today, inspector: '张三 李四', result: 'issues', issues: [{ issueTypeId: bootstrap.issueTypes[0].id, description: current.name + '问题', requirement: '清理', deadline: bootstrap.today }] } })
      }
      await go('/points')
      await page.getByTestId('point-ledger-mobile').click()
      let dialog = page.getByRole('dialog', { name: '导出台账', exact: true })
      await dialog.getByTestId('export-ledger').click()
      await expect(dialog).toContainText('请选择点位')
      await dialog.getByRole('button', { name: '取消', exact: true }).click()
      const boundaryQuery = new URLSearchParams({ from: bootstrap.today, to: bootstrap.today })
      for (let index = 0; index < 200; index++) boundaryQuery.append('pointId', point.id)
      const boundary = await fetch(directOrigin + '/api/exports/inspection-ledger?' + boundaryQuery)
      assert.equal(boundary.status, 200, 'The maximum point selection must fit the request-line limit')
      await boundary.arrayBuffer()
      boundaryQuery.append('pointId', point.id)
      const excessive = await fetch(directOrigin + '/api/exports/inspection-ledger?' + boundaryQuery)
      assert.equal(excessive.status, 400, 'Keep the server-side 200-point bound')
      await excessive.arrayBuffer()
      const destination = path.join(evidence, 'round3-ledgers'); await mkdir(destination, { recursive: true })
      for (const kind of ['inspection', 'rectification', 'remediation']) {
        await page.getByTestId('point-ledger-mobile').click()
        dialog = page.getByRole('dialog', { name: '导出台账', exact: true })
        await dialog.getByTestId('ledger-kind-' + kind).click()
        await dialog.getByTestId('ledger-point-search').fill('本轮')
        await dialog.getByRole('checkbox', { name: point.name, exact: true }).check()
        await dialog.getByRole('checkbox', { name: '本轮临时丙点位', exact: true }).check()
        const request = page.waitForRequest(r => new URL(r.url()).pathname === '/api/exports/' + kind + '-ledger')
        const download = page.waitForEvent('download')
        await dialog.getByTestId('export-ledger').click()
        const url = new URL((await request).url())
        assert.deepEqual(url.searchParams.getAll('pointId').sort(), [point.id, temporaryRemediation.activity.pointId].sort())
        const file = path.join(destination, kind + '.docx'); await (await download).saveAs(file)
        const text = execFileSync('python3', ['-c', "import sys,zipfile,xml.etree.ElementTree as E; z=zipfile.ZipFile(sys.argv[1]); print(''.join(E.fromstring(z.read('word/document.xml')).itertext()))", file], { encoding: 'utf8' })
        assert(text.includes(point.name)); assert(!text.includes(excluded.name)); assert(!text.includes('乙点位整治不应出现'))
      }
    })

    await test('R3 people tags normalize delimiters, handle IME and preserve unfinished input', async () => {
      await go('/settings?tab=basic')
      const input = page.getByTestId('default-inspector')
      await clearNames(input)
      await pasteNames(input, '甲，乙,丙、丁；戊 己\n庚')
      await input.press('Enter')
      await expect(namesRoot(input).locator('.name-edit-tag')).toHaveCount(7)
      await input.dispatchEvent('compositionstart')
      await input.fill('辛')
      await input.dispatchEvent('keydown', { key: 'Enter', isComposing: true, keyCode: 229 })
      await expect(namesRoot(input).locator('.name-edit-tag')).toHaveCount(7)
      await input.dispatchEvent('compositionend', { data: '辛' })
      await input.press('Enter')
      await expect(namesRoot(input).locator('.name-edit-tag')).toHaveCount(8)
      await input.fill('壬')
      const saved = response('/settings', 'PUT'); await page.getByTestId('settings-save').click(); assert.equal((await saved).status(), 200)
      assert.equal((await api('/settings')).defaultInspector, '甲 乙 丙 丁 戊 己 庚 辛 壬')
      await go('/inspections/new')
      await expect(namesRoot(page.getByTestId('inspection-inspector'))).toContainText('壬')
      await page.getByTestId('inspection-result-issues').click()
      const label = page.locator('.deadline-label')
      const bounds = await label.evaluate(element => ({ h: element.getBoundingClientRect().height, text: element.textContent, wrap: getComputedStyle(element).whiteSpace }))
      assert(bounds.text.includes('默认排查日后7天')); assert.equal(bounds.wrap, 'nowrap'); assert(bounds.h < 30)
      await page.getByTestId('temporary-point-mode').click()
      await expect(page.getByRole('link', { name: '选取', exact: true })).toHaveAttribute('href', 'https://ditu.gaode.com/ssr/coordinate-picker')
      await page.getByTestId('inspection-inspector').fill('最后未提交姓名')
      await page.reload({ waitUntil: 'networkidle' })
      await expect(namesRoot(page.getByTestId('inspection-inspector'))).toContainText('最后未提交姓名')
      const width = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: innerWidth }))
      assert(width.scroll <= width.width + 1)
      await page.screenshot({ path: path.join(evidence, 'round3-tags-and-deadline.png'), fullPage: true, animations: 'disabled' })
    })

    await test('R3 notice variables insert at caret and replace selection without blurring', async () => {
      await go('/settings?tab=template')
      const textarea = page.getByTestId('notice-template')
      await textarea.fill('前后')
      await textarea.evaluate(element => { element.focus(); element.setSelectionRange(1, 1); window.__noticeBlurs = 0; element.addEventListener('blur', () => window.__noticeBlurs++) })
      await page.getByRole('button', { name: '插入{点位}', exact: true }).click()
      await expect(textarea).toHaveValue('前{点位}后')
      assert.equal(await page.evaluate(() => window.__noticeBlurs), 0)
      await expect(textarea).toBeFocused()
      await textarea.evaluate(element => element.setSelectionRange(0, 1))
      await page.getByRole('button', { name: '插入{社区}', exact: true }).click()
      await expect(textarea).toHaveValue('{社区}{点位}后')
      await expect(textarea).toBeFocused()
      assert.equal(await page.evaluate(() => window.__noticeBlurs), 0)
      const saved = response('/settings', 'PUT'); await page.getByRole('button', { name: '保存', exact: true }).click(); assert.equal((await saved).status(), 200)
      assert.equal((await api('/settings')).noticeTemplate, '{社区}{点位}后')
      await page.screenshot({ path: path.join(evidence, 'round3-template.png'), fullPage: true, animations: 'disabled' })
    })
    assert.deepEqual(errors, [], 'Round-three flows caused unhandled errors')
  } catch (error) {
    await page.screenshot({ path: path.join(evidence, 'round3-failure.png'), fullPage: true }).catch(() => {})
    await writeFile(path.join(evidence, 'round3-failure.html'), await page.content()).catch(() => {})
    throw error
  } finally {
    await api('/settings', { method: 'PUT', body: originalSettings })
    await context.close()
  }
}
